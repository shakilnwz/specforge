# SpecForge installer library: what install.sh, update.sh and uninstall.sh share.
#
# Not a command, and never run on its own. release.sh inlines it into each of the three scripts, in
# place of the line that reads it, so every published script stands alone and is safe to pipe from
# curl. From a checkout, each script reads it from beside itself.
#
# Definitions only: constants and functions. Nothing here runs.

SPECFORGE_VERSION='@SPECFORGE_VERSION@'
SPECFORGE_REPO='@SPECFORGE_REPO@'

BEGIN_MARK='<!-- specforge:begin -->'
END_MARK='<!-- specforge:end -->'
GEN_MARK='<!-- Generated by .ai/bin/sync-rules from'
LOCK_REL='.ai/specforge.lock'
INCOMING='.specforge-incoming'
KNOWN_AGENTS='claude codex cursor copilot windsurf antigravity gemini kiro'
KNOWN_PROFILES='laravel dotnet nextjs react vue'
AGENT_DIRS='.claude/rules .cursor/rules .github/instructions .windsurf/rules .agents/rules .kiro/steering'
TRACKED_DIRS='.claude .claude/rules .cursor .cursor/rules .github .github/instructions .windsurf .windsurf/rules .agents .agents/rules .kiro .kiro/steering .gemini'

# ---------------------------------------------------------------------------------------------
# Output

say() { printf '%s\n' "$*"; }
err() { printf 'specforge: %s\n' "$*" >&2; }
die() { err "$*"; exit 1; }
usage_error() { err "$*"; printf "Run '%s.sh --help' for usage.\n" "$CMD" >&2; exit 2; }
tty_say() { printf '%s\n' "$*" > /dev/tty; }

show_answer_keys() {
    printf '%s\n' \
        'answers, one key=value per line; a project'"'"'s .ai/specforge.lock is itself an answers file' \
        '  state=new|existing' \
        "  app=<path> <profile>...   one line per path; profiles: $KNOWN_PROFILES" \
        "  agents=<agent>...         any of: $KNOWN_AGENTS; or none" \
        '  gherkin=yes|no' \
        '  host=github|other'
}

# ---------------------------------------------------------------------------------------------
# Small helpers

has_word() {
    case " $1 " in *" $2 "*) return 0 ;; esac
    return 1
}

trim() {
    s=$1
    s=${s#"${s%%[![:space:]]*}"}
    s=${s%"${s##*[![:space:]]}"}
    printf '%s' "$s"
}

squeeze() {
    # Collapses runs of whitespace into single spaces.
    printf '%s\n' "$*" | awk '{ $1 = $1; print }'
}

is_stamped() {
    case $SPECFORGE_VERSION in @*) return 1 ;; esac
    return 0
}

relpath() {
    if [ "$1" = "$TARGET" ]; then printf '.\n'; else printf '%s\n' "${1#"$TARGET"/}"; fi
}

norm_path() {
    p=$1
    while :; do
        case $p in ./?*) p=${p#./} ;; *?/) p=${p%/} ;; *) break ;; esac
    done
    printf '%s\n' "$p"
}

profile_name() {
    case $1 in
        laravel) printf 'Laravel' ;;
        dotnet) printf '.NET' ;;
        nextjs) printf 'Next.js' ;;
        react) printf 'React' ;;
        vue) printf 'Vue' ;;
    esac
}

agent_name() {
    case $1 in
        claude) printf 'Claude Code' ;;
        codex) printf 'Codex' ;;
        cursor) printf 'Cursor' ;;
        copilot) printf 'GitHub Copilot' ;;
        windsurf) printf 'Windsurf' ;;
        antigravity) printf 'Antigravity' ;;
        gemini) printf 'Gemini CLI' ;;
        kiro) printf 'Kiro' ;;
    esac
}

agent_rules() {
    # Where .ai/bin/sync-rules delivers the rules to the agent: shown beside it in the menu.
    case $1 in
        claude) printf '.claude/rules' ;;
        codex) printf 'reads AGENTS.md' ;;
        cursor) printf '.cursor/rules' ;;
