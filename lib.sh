# ---------------------------------------------------------------------------------------------
# What to install: profiles, the manifest's selection, rendered files

implied_by() {
    awk -v p="$1" '$1 == "implies" && $2 == p { print $3 }' "$SRC/manifest"
}

expand_profiles() {
    out=
    for p in $1; do
        has_word "$out" "$p" || out="$out $p"
        for q in $(implied_by "$p"); do has_word "$out" "$q" || out="$out $q"; done
    done
    squeeze "$out"
}

compute_profiles() {
    if [ -s "$WORK/apps" ]; then
        all=$(awk '{ $1 = ""; print }' "$WORK/apps" | tr '\n' ' ')
        PROFILES=$(expand_profiles "$all")
    else
        PROFILES=$KNOWN_PROFILES
    fi
}

select_targets() {
    (cd "$SRC/template" && find . -type f | sed 's|^\./||' | LC_ALL=C sort) > "$WORK/template.files"
    awk -v profiles=" $PROFILES " -v gherkin="$A_GHERKIN" -v host="$A_HOST" '
        /^[[:space:]]*(#|$)/ { next }
        $1 == "implies" { next }
        {
            sel = $1; path = $2; mode = ($3 == "" ? "file" : $3)
            if (mode != "file" && mode != "block" && mode != "seed" && mode != "generated") {
                print "manifest: unknown mode " mode > "/dev/stderr"; exit 3
            }
            ok = 0
            if (sel == "always") ok = 1
            else if (sel ~ /^profile=/) { if (index(profiles, " " substr(sel, 9) " ")) ok = 1 }
            else if (sel ~ /^gherkin=/) { if (substr(sel, 9) == gherkin) ok = 1 }
            else if (sel ~ /^host=/) { if (substr(sel, 6) == host) ok = 1 }
            else { print "manifest: unknown selector " sel > "/dev/stderr"; exit 3 }
            print path "\t" mode "\t" ok
        }' "$SRC/manifest" > "$WORK/manifest.eval" || die 'the manifest is malformed'
    awk -F '\t' '
        NR == FNR { p[NR] = $1; m[NR] = $2; k[NR] = $3; n = NR; next }
        {
            f = $0; matched = 0; inc = 0; mode = "file"
            for (i = 1; i <= n; i++) {
                if (p[i] == f || (substr(p[i], length(p[i])) == "/" && index(f, p[i]) == 1)) {
                    matched = 1; mode = m[i]; if (k[i] == 1) inc = 1
                }
            }
            if (!matched || inc) print mode "\t" f
        }' "$WORK/manifest.eval" "$WORK/template.files" > "$WORK/targets"
    cut -f2 "$WORK/targets" > "$WORK/target.paths"
}

stacks_rows() {
    while read -r path profs; do
        [ -n "$path" ] || continue
        names=
        links=
        for p in $(expand_profiles "$profs"); do
            names="$names${names:+ · }$(profile_name "$p")"
            links="$links${links:+ · }[\`stack-$p.md\`](docs/conventions/stack-$p.md)"
        done
        printf '| `%s` | %s <!-- bootstrap: versions --> | %s |\n' "$path" "$names" "$links"
    done < "$WORK/apps"
}

render_sources() {
    mkdir -p "$WORK/render/.ai"
    awk -v list=" $A_AGENTS " '
        /^# [a-z]+$/ { k = substr($0, 3); if (index(list, " " k " ")) { print k; next } }
        { print }' "$SRC/template/.ai/agents" > "$WORK/render/.ai/agents"
    stacks_rows > "$WORK/stacks"
    if [ -s "$WORK/stacks" ]; then
        awk -v rows="$WORK/stacks" '
            !done && index($0, "| <!-- bootstrap: `<path>` -->") == 1 {
                while ((getline l < rows) > 0) print l
                done = 1; next
            }
            { print }' "$SRC/template/AGENTS.md" > "$WORK/render/AGENTS.md"
    fi
}

source_of() {
    if [ -f "$WORK/render/$1" ]; then printf '%s\n' "$WORK/render/$1"; else printf '%s\n' "$SRC/template/$1"; fi
}

# ---------------------------------------------------------------------------------------------
# Writing, recording, the managed block

record() { printf '%s\n' "$*" >> "$WORK/lock.new"; }
note() { printf '%s\t%s\n' "$1" "$2" >> "$WORK/notes"; }

ensure_dir() {
    local d=$1
    [ -d "$d" ] && return 0
    ensure_dir "$(dirname "$d")" || return 1
    mkdir "$d" || return 1
    record "dir - $(relpath "$d")"
}

put() {
    # put <source> <destination>: atomic within the destination's directory, modes preserved.
    [ "$DRY_RUN" = 1 ] && return 0
    ensure_dir "$(dirname "$2")" || die "cannot create the directory for $2"
    cp -p "$1" "$2.specforge-tmp.$$" && mv -f "$2.specforge-tmp.$$" "$2" || die "cannot write $2"
}

drop() {
    [ "$DRY_RUN" = 1 ] && return 0
    rm -f "$1"
}

lock_entry() {
    awk -v p="$1" '
        ($1 == "file" || $1 == "seed" || $1 == "block" || $1 == "generated" || $1 == "deleted") && $NF == p {
            print; exit
        }' "$WORK/lock.old"
}

extract_block() {
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
        !done && $0 == b { inb = 1; found = 1; next }
        inb && $0 == e { inb = 0; done = 1; next }
        inb { print }
        END { if (!done) exit 1 }' "$1"
}

replace_block() {
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" -v nb="$2" '
        !done && $0 == b { print; while ((getline l < nb) > 0) print l; close(nb); skip = 1; next }
        skip && $0 == e { skip = 0; done = 1; print; next }
        !skip { print }' "$1"
}

append_block() {
    cat "$1"
    [ -z "$(tail -c 1 "$1")" ] || printf '\n'
    printf '\n%s\n' "$BEGIN_MARK"
    cat "$2"
    printf '%s\n' "$END_MARK"
}

strip_block() {
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
        { line[++n] = $0 }
        END {
            s = 0; t = 0
            for (i = 1; i <= n; i++) if (line[i] == b) { s = i; break }
            for (j = s; s && j <= n; j++) if (line[j] == e) { t = j; break }
            if (s && t && s > 1 && line[s - 1] == "" && (t == n || line[t + 1] == "")) s--
            for (i = 1; i <= n; i++) if (!(s && t && i >= s && i <= t)) print line[i]
        }' "$1"
}

write_incoming() {
    # write_incoming <source> <path>: the kit's complete version beside the project's file.
    put "$1" "$TARGET/$2$INCOMING"
    record "incoming $(hash_file "$1") $2$INCOMING"
    note kept "$2"
}

# ---------------------------------------------------------------------------------------------
# The policy, per file

apply_file() {
    # apply_file <path> <file|seed>
    p=$1
    kind=$2
    src=$(source_of "$p")
    dest="$TARGET/$p"
    new=$(hash_file "$src")
    set -- $(lock_entry "$p")
    okind=${1-}
    osha=${2-}
    if [ "$okind" = deleted ]; then record "deleted - $p"; note skipped "$p"; return 0; fi
    if [ ! -e "$dest" ] && [ ! -L "$dest" ]; then
        if [ -n "$okind" ]; then record "deleted - $p"; note skipped "$p"; return 0; fi
        put "$src" "$dest"
        record "$kind $new $p"
        note wrote "$p"
        return 0
    fi
    if [ -L "$dest" ] || [ ! -f "$dest" ]; then write_incoming "$src" "$p"; return 0; fi
    cur=$(hash_file "$dest")
    if [ "$cur" = "$new" ]; then record "$kind $new $p"; note unchanged "$p"; return 0; fi
    if [ -n "$okind" ]; then
        if [ "$kind" = seed ]; then record "seed $osha $p"; note unchanged "$p"; return 0; fi
        if [ "$cur" = "$osha" ]; then
            put "$src" "$dest"
            record "$kind $new $p"
            note updated "$p"
            return 0
        fi
        if [ "$new" = "$osha" ]; then
            # Changed by the project, not by the kit since it was last offered: theirs stands.
            record "$kind $osha $p"
            note unchanged "$p"
            return 0
        fi
    fi
    # The lock remembers the version offered, so the next update stays quiet until it changes.
    record "$kind $new $p"
    write_incoming "$src" "$p"
}

apply_block() {
    # apply_block <path>: only the text between the markers is the kit's.
    p=$1
    src=$(source_of "$p")
    dest="$TARGET/$p"
    extract_block "$src" > "$WORK/block.new" || die "the kit's $p has no specforge block"
    nb=$(hash_file "$WORK/block.new")
    set -- $(lock_entry "$p")
    okind=${1-}
    obsha=${2-}
    ofsha=${3-}
    if [ "$okind" = deleted ]; then record "deleted - $p"; note skipped "$p"; return 0; fi
    if [ ! -e "$dest" ] && [ ! -L "$dest" ]; then
        if [ -n "$okind" ]; then record "deleted - $p"; note skipped "$p"; return 0; fi
        put "$src" "$dest"
        record "block $nb $(hash_file "$src") $p"
        note wrote "$p"
        return 0
    fi
    if [ -L "$dest" ] || [ ! -f "$dest" ]; then write_incoming "$src" "$p"; return 0; fi
    cf=$(hash_file "$dest")
    if extract_block "$dest" > "$WORK/block.cur"; then
        cb=$(hash_file "$WORK/block.cur")
        if [ "$cb" = "$nb" ]; then
            if [ -n "$ofsha" ] && [ "$cf" = "$ofsha" ]; then record "block $nb $ofsha $p"; else record "block $nb - $p"; fi
            note unchanged "$p"
            return 0
        fi
        if [ -n "$okind" ] && [ "$cb" = "$obsha" ]; then
            replace_block "$dest" "$WORK/block.new" > "$WORK/merged"
            put "$WORK/merged" "$dest"
            if [ -n "$ofsha" ] && [ "$cf" = "$ofsha" ]; then
                record "block $nb $(hash_file "$WORK/merged") $p"
            else
                record "block $nb - $p"
            fi
            note updated "$p"
            return 0
        fi
        if [ -n "$okind" ] && [ "$nb" = "$obsha" ]; then
            record "block $obsha - $p"
            note unchanged "$p"
            return 0
        fi
        record "block $nb - $p"
        write_incoming "$src" "$p"
        return 0
    fi
    if [ -n "$okind" ]; then
        # The markers were removed: the file is the project's, offered the kit's version only when
        # that version changes.
        record "block $nb - $p"
        if [ "$nb" = "$obsha" ]; then note unchanged "$p"; else write_incoming "$src" "$p"; fi
        return 0
    fi
    if [ "$p" = CLAUDE.md ] && grep -q '^@AGENTS\.md' "$dest"; then
        note unchanged "$p"
        return 0
    fi
    append_block "$dest" "$WORK/block.new" > "$WORK/merged"
    put "$WORK/merged" "$dest"
    record "block $nb - $p"
    note appended "$p"
    if [ "$p" = AGENTS.md ]; then write_incoming "$src" "$p"; fi
}

apply_dropped() {
    # Files the kit installed that are no longer selected: taken back while unmodified.
    awk '$1 == "file" || $1 == "seed" { print $2, $NF }' "$WORK/lock.old" > "$WORK/dropped"
    while read -r sha p; do
        grep -qxF "$p" "$WORK/target.paths" && continue
        dest="$TARGET/$p"
        if [ -f "$dest" ] && [ ! -L "$dest" ] && [ "$(hash_file "$dest")" = "$sha" ]; then
            drop "$dest"
            note removed "$p"
        elif [ -e "$dest" ]; then
            note left "$p"
        fi
    done < "$WORK/dropped"
}

carry_over() {
    # Directories the installer created, and incoming files not yet reconciled.
    while read -r kind sha p; do
        case $kind in
            dir) [ -d "$TARGET/$p" ] && record "dir - $p" ;;
            incoming) [ -f "$TARGET/$p" ] && record "incoming $sha $p" ;;
        esac
    done < "$WORK/lock.old"
}

run_sync() {
    SYNC_OUT=
    SYNC_STATUS=0
    if [ "$DRY_RUN" = 1 ]; then return 0; fi
    : > "$WORK/dirs.before"
    for d in $TRACKED_DIRS; do [ -e "$TARGET/$d" ] && printf '%s\n' "$d" >> "$WORK/dirs.before"; done
    gem_before=0
    [ -e "$TARGET/.gemini/settings.json" ] && gem_before=1
    if [ -x "$TARGET/.ai/bin/sync-rules" ]; then
        SYNC_OUT=$("$TARGET/.ai/bin/sync-rules" 2>&1) || SYNC_STATUS=$?
    else
        SYNC_OUT='.ai/bin/sync-rules is missing or not executable: agent rule files were not generated'
        SYNC_STATUS=1
    fi
    for d in $TRACKED_DIRS; do
        if [ -d "$TARGET/$d" ] && ! grep -qxF "$d" "$WORK/dirs.before"; then record "dir - $d"; fi
    done
    if [ -f "$TARGET/.ai/rules/index.md" ]; then
        record "generated $(hash_file "$TARGET/.ai/rules/index.md") .ai/rules/index.md"
    fi
    old=$(awk '$1 == "generated" && $NF == ".gemini/settings.json"' "$WORK/lock.old")
    if [ -n "$old" ] && [ -f "$TARGET/.gemini/settings.json" ]; then
        record "$old"
    elif [ "$gem_before" = 0 ] && [ -f "$TARGET/.gemini/settings.json" ]; then
        record "generated $(hash_file "$TARGET/.gemini/settings.json") .gemini/settings.json"
    fi
}

write_lock() {
    [ "$DRY_RUN" = 1 ] && return 0
    {
        printf '# Written by the SpecForge installer. Do not edit; commit it with the project.\n'
        printf 'version %s\n' "$KIT_VERSION"
        printf 'installed %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
        printf 'commit %s\n' "$GIT_COMMIT"
        printf 'answer state=%s\n' "$A_STATE"
        while read -r line; do [ -n "$line" ] && printf 'answer app=%s\n' "$line"; done < "$WORK/apps"
        printf 'answer agents=%s\n' "$A_AGENTS"
        printf 'answer gherkin=%s\n' "$A_GHERKIN"
        printf 'answer host=%s\n' "$A_HOST"
        # One entry per path, the last recorded winning; sorted by path.
        awk '{ last[$NF] = $0; if (!($NF in seen)) { seen[$NF] = 1; order[++n] = $NF } }
             END { for (i = 1; i <= n; i++) print order[i] "\t" last[order[i]] }' "$WORK/lock.new" |
            LC_ALL=C sort | cut -f2-
    } > "$WORK/lock.final"
    put "$WORK/lock.final" "$LOCK"
}

# ---------------------------------------------------------------------------------------------
# Reporting

count() { awk -F '\t' -v a="$1" '$1 == a' "$WORK/notes" | wc -l | tr -d ' '; }

list() {
    awk -F '\t' -v a="$1" '$1 == a { print "    " $2 }' "$WORK/notes"
}

summarize() {
    say ''
    if [ "$DRY_RUN" = 1 ]; then say "Dry run: SpecForge $KIT_VERSION would change $TARGET as follows. Nothing was changed."; fi
    say "  wrote $(count wrote), updated $(count updated), appended to $(count appended), unchanged $(count unchanged), kept yours $(count kept), removed $(count removed)"
    if [ "$(count appended)" -gt 0 ]; then
        say "  The rules' block was appended to your file:"
        list appended
    fi
    if [ "$(count kept)" -gt 0 ]; then
        say "  Kept yours; the kit's version is beside each as <file>$INCOMING:"
        list kept
    fi
    if [ "$(count left)" -gt 0 ]; then
        say '  No longer part of the rules, but kept because you changed them:'
        list left
    fi
    if [ "$(count skipped)" -gt 0 ]; then
        say '  Deleted by you, and not restored:'
        list skipped
    fi
    if [ -n "${SYNC_OUT-}" ]; then
        problems=$(printf '%s\n' "$SYNC_OUT" | grep -v '^wrote: ' | grep -v '^removed: ' || true)
        if [ "${SYNC_STATUS:-0}" != 0 ] || [ -n "$problems" ]; then
            say '  .ai/bin/sync-rules reported:'
            printf '%s\n' "$problems" | sed 's/^/    /'
        fi
    fi
}

handover() {
    [ "$DRY_RUN" = 1 ] && return 0
    say ''
    if [ -n "$A_AGENTS" ]; then
        say "Agents: $A_AGENTS. Their rule files are generated from .ai/rules/ by .ai/bin/sync-rules."
    else
        say 'Agents: none chosen. Every agent still reads AGENTS.md; list yours in .ai/agents, then run .ai/bin/sync-rules.'
    fi
    say ''
    say 'Next:'
    n=1
    if [ "$CMD" = install ]; then
        if [ "$A_STATE" = new ]; then
            say "  $n. Open the project in your agent and say: Run the bootstrap prompt."
        else
            say "  $n. Open the project in your agent and say: Run the adopt prompt."
        fi
        n=$((n + 1))
    fi
    if [ "$(count kept)" -gt 0 ]; then
        say "  $n. Reconcile each <file>$INCOMING, then delete it; .ai/bin/check lists them until then."
        n=$((n + 1))
    fi
    if [ "$CMD" = update ] && [ "${APPS_CHANGED:-0}" = 1 ]; then
        say "  $n. The apps changed: bring the Stacks table in AGENTS.md in line with them."
        n=$((n + 1))
    fi
    if [ "$CMD" = install ]; then
        say "  $n. Add .ai/bin/check to CI, beside each app's lint, type check and tests."
        n=$((n + 1))
    fi
    if detect_boost; then
        say "  $n. Laravel Boost is installed: run php artisan boost:install to refresh its guidelines."
        n=$((n + 1))
    fi
    if [ -e "$TARGET/.git" ]; then
        say "  $n. Commit the rules together with $LOCK_REL."
    fi
}

# ---------------------------------------------------------------------------------------------
# What install.sh and update.sh share, once the answers are settled

install_or_update() {
    compute_profiles
    render_sources
    select_targets
    carry_over
    while IFS="$(printf '\t')" read -r mode p; do
        case $mode in
            file | seed) apply_file "$p" "$mode" ;;
            block) apply_block "$p" ;;
            generated) ;;
        esac
    done < "$WORK/targets"
    apply_dropped
    run_sync
    write_lock
    summarize
    handover
}
