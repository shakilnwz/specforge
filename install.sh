#!/usr/bin/env bash
#
# SpecForge installer: adds the SpecForge rules (coding, spec, audit and documentation rules, with
# the prompts and templates that apply them) to a project directory, new or existing.
#
#   curl -fsSL https://github.com/shakilnwz/specforge/releases/latest/download/install.sh | bash -s -- install
#
# Run `install.sh help` for commands and options.
#
# It never creates a project, application code or project infrastructure; never overwrites a file
# it did not install unmodified; never commits, stages or branches. Portable: bash 3.2 or later,
# curl, tar and POSIX tools; git only to report on a work tree, when present.
#
# Every statement lives in a function and the only call is on the last line, so a download cut short
# runs nothing.

SPECFORGE_VERSION='@SPECFORGE_VERSION@'
SPECFORGE_REPO='@SPECFORGE_REPO@'

BEGIN_MARK='<!-- specforge:begin -->'
END_MARK='<!-- specforge:end -->'
GEN_MARK='<!-- Generated by .ai/bin/sync-rules from'
LOCK_REL='.ai/specforge.lock'
INCOMING='.specforge-incoming'
KNOWN_AGENTS='claude codex cursor copilot windsurf antigravity gemini kiro'
KNOWN_PROFILES='laravel dotnet nextjs react vue'
AGENT_DIRS='.claude/rules .cursor/rules .github/instructions .windsurf/rules .agents/rules .kiro/steering'
TRACKED_DIRS='.claude .claude/rules .cursor .cursor/rules .github .github/instructions .windsurf .windsurf/rules .agents .agents/rules .kiro .kiro/steering .gemini'

# ---------------------------------------------------------------------------------------------
# Output

say() { printf '%s\n' "$*"; }
err() { printf 'specforge: %s\n' "$*" >&2; }
die() { err "$*"; exit 1; }
usage_error() { err "$*"; printf "Run 'install.sh help' for usage.\n" >&2; exit 2; }
tty_say() { printf '%s\n' "$*" > /dev/tty; }

show_help() {
    cat <<'EOF'
SpecForge installer: adds the SpecForge rules to a project directory, new or existing.

usage: install.sh <command> [options]

commands
  install          add the rules to the project
  update           bring the rules to this installer's version; files you changed are kept
  remove           take back what was installed and is still unmodified
  help             this text

options
  --dir DIR        the project directory (default: the current one); it must already exist
  --answers FILE   answers as key=value lines, read and never run:
                     state=new|existing
                     app=<path> <profile>...   one per path; profiles: laravel dotnet nextjs react vue
                     agents=<agent>...         claude codex cursor copilot windsurf antigravity gemini kiro
                     gherkin=yes|no
                     host=github|other
                   A project's .ai/specforge.lock is a valid answers file.
  --yes            ask nothing: take what detection found
  --reconfigure    update only: ask the questions again
  --dry-run        print what would change, and change nothing
  --version vX.Y.Z install that release instead of this installer's own
  --from PATH      install from a local checkout or release tarball instead of downloading

A file you changed is never overwritten: the kit's version is written beside it as
<file>.specforge-incoming. What was installed is recorded in .ai/specforge.lock.
EOF
}

# ---------------------------------------------------------------------------------------------
# Small helpers

has_word() {
    case " $1 " in *" $2 "*) return 0 ;; esac
    return 1
}

trim() {
    s=$1
    s=${s#"${s%%[![:space:]]*}"}
    s=${s%"${s##*[![:space:]]}"}
    printf '%s' "$s"
}

squeeze() {
    # Collapses runs of whitespace into single spaces.
    printf '%s\n' "$*" | awk '{ $1 = $1; print }'
}

is_stamped() {
    case $SPECFORGE_VERSION in @*) return 1 ;; esac
    return 0
}

relpath() {
    if [ "$1" = "$TARGET" ]; then printf '.\n'; else printf '%s\n' "${1#"$TARGET"/}"; fi
}

norm_path() {
    p=$1
    while :; do
        case $p in ./?*) p=${p#./} ;; *?/) p=${p%/} ;; *) break ;; esac
    done
    printf '%s\n' "$p"
}

profile_name() {
    case $1 in
        laravel) printf 'Laravel' ;;
        dotnet) printf '.NET' ;;
        nextjs) printf 'Next.js' ;;
        react) printf 'React' ;;
        vue) printf 'Vue' ;;
    esac
}

pick_hasher() {
    if command -v sha256sum >/dev/null 2>&1; then HASHER=sha256sum
    elif command -v shasum >/dev/null 2>&1; then HASHER=shasum
    elif command -v openssl >/dev/null 2>&1; then HASHER=openssl
    else die 'no SHA-256 tool found: install sha256sum, shasum or openssl'
    fi
}

hash_file() {
    case $HASHER in
        sha256sum) sha256sum < "$1" | awk '{ print $1 }' ;;
        shasum) shasum -a 256 < "$1" | awk '{ print $1 }' ;;
        openssl) openssl dgst -sha256 < "$1" | awk '{ print $NF }' ;;
    esac
}

# ---------------------------------------------------------------------------------------------
# Arguments, target, workspace

parse_args() {
    CMD=${1-}
    [ $# -gt 0 ] && shift
    case $CMD in
        install | update | remove) ;;
        help | -h | --help) show_help; exit 0 ;;
        '') show_help >&2; exit 2 ;;
        *) usage_error "unknown command: $CMD" ;;
    esac
    TARGET=. ANSWERS_FILE= ASSUME_YES=0 RECONFIGURE=0 DRY_RUN=0 WANT_VERSION= FROM=
    while [ $# -gt 0 ]; do
        case $1 in
            --dir) [ $# -ge 2 ] || usage_error '--dir needs a directory'; TARGET=$2; shift 2 ;;
            --dir=*) TARGET=${1#--dir=}; shift ;;
            --answers) [ $# -ge 2 ] || usage_error '--answers needs a file'; ANSWERS_FILE=$2; shift 2 ;;
            --answers=*) ANSWERS_FILE=${1#--answers=}; shift ;;
            --version) [ $# -ge 2 ] || usage_error '--version needs a version'; WANT_VERSION=$2; shift 2 ;;
            --version=*) WANT_VERSION=${1#--version=}; shift ;;
            --from) [ $# -ge 2 ] || usage_error '--from needs a path'; FROM=$2; shift 2 ;;
            --from=*) FROM=${1#--from=}; shift ;;
            --yes | -y) ASSUME_YES=1; shift ;;
            --reconfigure) RECONFIGURE=1; shift ;;
            --dry-run) DRY_RUN=1; shift ;;
            *) usage_error "unknown option: $1" ;;
        esac
    done
    [ "$RECONFIGURE" = 0 ] || [ "$CMD" = update ] || usage_error '--reconfigure is an update option'
    case $WANT_VERSION in '' | v[0-9]*) ;; *) usage_error "not a version: $WANT_VERSION (expected vX.Y.Z)" ;; esac
    if [ -n "$ANSWERS_FILE" ]; then
        [ -f "$ANSWERS_FILE" ] || die "no such answers file: $ANSWERS_FILE"
        ANSWERS_FILE=$(cd "$(dirname "$ANSWERS_FILE")" && pwd -P)/$(basename "$ANSWERS_FILE")
    fi
    if [ -n "$FROM" ]; then
        [ -e "$FROM" ] || die "--from: no such file or directory: $FROM"
        FROM=$(cd "$(dirname "$FROM")" && pwd -P)/$(basename "$FROM")
    fi
}

resolve_target() {
    [ -d "$TARGET" ] || die "no such directory: $TARGET. SpecForge adds rules to a project directory; it does not create one"
    TARGET=$(cd "$TARGET" && pwd -P) || die "cannot enter $TARGET"
    [ "$TARGET" != / ] || die 'refusing to install into /'
    LOCK="$TARGET/$LOCK_REL"
}

make_work() {
    WORK=$(mktemp -d "${TMPDIR:-/tmp}/specforge.XXXXXX") || die 'cannot create a temporary directory'
    trap 'rm -rf "$WORK"' EXIT
    trap 'rm -rf "$WORK"; exit 130' INT TERM
    : > "$WORK/lock.old"
    : > "$WORK/lock.new"
    : > "$WORK/notes"
    : > "$WORK/apps"
}

# ---------------------------------------------------------------------------------------------
# The rules to install: a local checkout or tarball, or a verified release download

find_source_root() {
    if [ -f "$1/manifest" ]; then printf '%s\n' "$1"; return 0; fi
    set +f
    for d in "$1"/*/; do
        if [ -f "$d/manifest" ]; then set -f; printf '%s\n' "${d%/}"; return 0; fi
    done
    set -f
    printf '%s\n' "$1"
}

fetch() {
    if [ -n "$3" ]; then
        curl -fsSL --proto "$3" --tlsv1.2 -o "$2" "$1"
    else
        curl -fsSL -o "$2" "$1"
    fi
}

download() {
    command -v curl >/dev/null 2>&1 || die 'curl is required to download the rules (or pass --from)'
    version=$WANT_VERSION
    if [ -z "$version" ]; then
        is_stamped || die 'this installer is not a release build: pass --from <checkout> or --version vX.Y.Z'
        version=$SPECFORGE_VERSION
    fi
    if [ -n "${SPECFORGE_BASE_URL:-}" ]; then
        base=${SPECFORGE_BASE_URL%/}
        proto=
    else
        case $SPECFORGE_REPO in @*) die 'this installer names no repository: pass --from <checkout>' ;; esac
        base="https://github.com/$SPECFORGE_REPO/releases/download"
        proto='=https'
    fi
    name="specforge-$version.tar.gz"
    say "Downloading SpecForge $version"
    fetch "$base/$version/$name" "$WORK/$name" "$proto" || die "download failed: $base/$version/$name"
    fetch "$base/$version/$name.sha256" "$WORK/$name.sha256" "$proto" ||
        die "download failed: $base/$version/$name.sha256"
    want=$(awk 'NR == 1 { print $1 }' "$WORK/$name.sha256")
    got=$(hash_file "$WORK/$name")
    if [ -z "$want" ] || [ "$want" != "$got" ]; then
        die "checksum mismatch for $name: nothing was installed"
    fi
    mkdir "$WORK/src" && tar -xzf "$WORK/$name" -C "$WORK/src" || die "cannot unpack $name"
    SRC=$(find_source_root "$WORK/src")
}

fetch_source() {
    if [ -n "$FROM" ]; then
        if [ -d "$FROM" ]; then
            SRC=$FROM
        else
            mkdir "$WORK/src" && tar -xzf "$FROM" -C "$WORK/src" || die "cannot unpack $FROM"
            SRC=$(find_source_root "$WORK/src")
        fi
    else
        download
    fi
    [ -d "$SRC/template" ] && [ -f "$SRC/manifest" ] ||
        die "$SRC is not a SpecForge release: it has no template/ or manifest"
    if [ -f "$SRC/VERSION" ]; then
        KIT_VERSION=$(sed -n 1p "$SRC/VERSION")
    elif [ -n "$FROM" ]; then
        KIT_VERSION=dev
    else
        KIT_VERSION=$version
    fi
}

# ---------------------------------------------------------------------------------------------
# Detection: what the project already is. Read-only.

pkg_has() {
    grep -Eq "\"$2\"[[:space:]]*:" "$1" 2>/dev/null
}

add_detected() {
    printf '%s %s\n' "$1" "$2" >> "$WORK/detected.raw"
}

detect_apps() {
    : > "$WORK/detected.raw"
    find "$TARGET" -maxdepth 4 \
        \( -name .git -o -name node_modules -o -name vendor -o -name bin -o -name obj \
           -o -name .next -o -name dist -o -name build -o -name .ai -o -name docs \) -prune -o \
        -type f \( -name artisan -o -name package.json -o -name '*.sln' -o -name '*.slnx' \
                   -o -name '*.csproj' \) -print 2>/dev/null | LC_ALL=C sort > "$WORK/found"
    has_sln=0
    grep -Eq '\.slnx?$' "$WORK/found" && has_sln=1
    while IFS= read -r f; do
        d=$(dirname "$f")
        rel=$(relpath "$d")
        case $f in
            */artisan)
                grep -q '"laravel/framework"' "$d/composer.json" 2>/dev/null && add_detected "$rel" laravel ;;
            *.sln | *.slnx)
                add_detected "$rel" dotnet ;;
            *.csproj)
                [ "$has_sln" = 0 ] && grep -q 'Microsoft.NET.Sdk.Web' "$f" && add_detected "$rel" dotnet ;;
            */package.json)
                if pkg_has "$f" next; then
                    add_detected "$rel" nextjs
                else
                    front=
                    if pkg_has "$f" react; then front=react; elif pkg_has "$f" vue; then front=vue; fi
                    if [ -n "$front" ]; then
                        if [ -f "$d/artisan" ] && [ -d "$d/resources/js" ]; then
                            if [ "$rel" = . ]; then add_detected resources/js "$front"
                            else add_detected "$rel/resources/js" "$front"; fi
                        else
                            add_detected "$rel" "$front"
                        fi
                    fi
                fi ;;
        esac
    done < "$WORK/found"
    # One line per path, its profiles in the order found.
    awk '{
            if (!($1 in seen)) { seen[$1] = 1; order[++n] = $1 }
            if (index(" " prof[$1] " ", " " $2 " ") == 0) prof[$1] = prof[$1] (prof[$1] == "" ? "" : " ") $2
        }
        END { for (i = 1; i <= n; i++) print order[i], prof[order[i]] }' "$WORK/detected.raw" > "$WORK/detected.apps"
}

detect_state() {
    if [ -s "$WORK/detected.apps" ]; then printf 'existing\n'; return 0; fi
    set +f
    for e in "$TARGET"/* "$TARGET"/.[!.]* "$TARGET"/..?*; do
        [ -e "$e" ] || [ -L "$e" ] || continue
        case ${e##*/} in
            .git | .gitignore | .gitattributes | .editorconfig | .DS_Store | .idea | .vscode | .github | \
            README* | LICENSE* | AGENTS.md | CLAUDE.md | GEMINI.md | .ai | docs) continue ;;
        esac
        set -f
        printf 'existing\n'
        return 0
    done
    set -f
    printf 'new\n'
}

detect_agents() {
    found=
    t=$TARGET
    { [ -e "$t/.claude" ] || [ -e "$t/CLAUDE.md" ]; } && found="$found claude"
    [ -e "$t/.codex" ] && found="$found codex"
    { [ -e "$t/.cursor" ] || [ -e "$t/.cursorrules" ]; } && found="$found cursor"
    { [ -e "$t/.github/copilot-instructions.md" ] || [ -d "$t/.github/instructions" ]; } && found="$found copilot"
    { [ -e "$t/.windsurf" ] || [ -e "$t/.windsurfrules" ] || [ -e "$t/.devin" ]; } && found="$found windsurf"
    { [ -e "$t/.agents" ] || [ -e "$t/.agent" ]; } && found="$found antigravity"
    { [ -e "$t/.gemini" ] || [ -e "$t/GEMINI.md" ]; } && found="$found gemini"
    [ -e "$t/.kiro" ] && found="$found kiro"
    squeeze "$found"
}

detect_host() {
    if [ -d "$TARGET/.github" ]; then printf 'github\n'; return 0; fi
    if [ -f "$TARGET/.git/config" ]; then
        if grep -q 'github\.com' "$TARGET/.git/config"; then printf 'github\n'; return 0; fi
        if grep -Eq 'gitlab|bitbucket|dev\.azure\.com|codeberg' "$TARGET/.git/config"; then printf 'other\n'; return 0; fi
    fi
    printf 'github\n'
}

detect_gherkin() {
    if [ -d "$TARGET/features" ]; then printf 'yes\n'; else printf 'no\n'; fi
}

detect_boost() {
    while read -r path profs; do
        has_word "$profs" laravel || continue
        if [ "$path" = . ]; then c="$TARGET/composer.json"; else c="$TARGET/$path/composer.json"; fi
        grep -q '"laravel/boost"' "$c" 2>/dev/null && return 0
    done < "$WORK/apps"
    return 1
}

git_report() {
    GIT_COMMIT=none
    [ -e "$TARGET/.git" ] || return 0
    if command -v git >/dev/null 2>&1; then
        GIT_COMMIT=$(git -C "$TARGET" rev-parse --short HEAD 2>/dev/null) || GIT_COMMIT=none
        [ -n "$GIT_COMMIT" ] || GIT_COMMIT=none
        dirty=$(git -C "$TARGET" status --porcelain 2>/dev/null | wc -l | tr -d ' ')
        if [ "${dirty:-0}" -gt 0 ]; then
            say "git: $dirty uncommitted change(s) in the work tree. SpecForge commits nothing;"
            say "     review what it wrote with 'git status' afterwards."
        fi
    else
        say 'git: a work tree, but git is not installed, so the commit is not recorded.'
    fi
}

# ---------------------------------------------------------------------------------------------
# Answers: detected or recorded defaults, an answers file, and the questions

valid_app() {
    # valid_app <path> <profile>...
    path=$1
    shift
    case $path in '' | /* | *..*) return 1 ;; esac
    case $path in *[!A-Za-z0-9._/-]*) return 1 ;; esac
    [ $# -gt 0 ] || return 1
    for p in "$@"; do has_word "$KNOWN_PROFILES" "$p" || return 1; done
    return 0
}

add_app() {
    # add_app "<path> <profile>...": validates, normalises, appends to the apps list.
    line=$(squeeze "$1")
    set -- $line
    valid_app "$@" || return 1
    path=$(norm_path "$1")
    shift
    printf '%s %s\n' "$path" "$*" >> "$WORK/apps"
}

load_answers_file() {
    apps_seen=0
    : > "$WORK/apps.answers"
    while IFS= read -r line || [ -n "$line" ]; do
        line=$(trim "$line")
        case $line in '' | '#'*) continue ;; esac
        case $line in answer[[:space:]]*) line=$(trim "${line#answer}") ;; esac
        case $line in *=*) ;; *) continue ;; esac
        key=$(trim "${line%%=*}")
        val=$(squeeze "${line#*=}")
        case $key in
            state) A_STATE=$val ;;
            app)
                apps_seen=1
                add_app "$val" || die "answers file: not a valid app line: '$val' (a relative path, then profiles from: $KNOWN_PROFILES)"
                ;;
            agents) A_AGENTS=$val ;;
            gherkin) A_GHERKIN=$val ;;
            host) A_HOST=$val ;;
            version | installed | commit | file | seed | block | generated | deleted | incoming | dir) ;;
            *) die "answers file: unknown key '$key'" ;;
        esac
    done < "$ANSWERS_FILE"
    [ "$A_AGENTS" = none ] && A_AGENTS=
    return 0
}

load_answers() {
    # The answers file replaces the defaults key by key; app lines replace the detected apps as a set.
    cp "$WORK/apps" "$WORK/apps.defaults"
    : > "$WORK/apps"
    load_answers_file
    if [ "$apps_seen" = 0 ]; then cp "$WORK/apps.defaults" "$WORK/apps"; fi
}

validate_answers() {
    case $A_STATE in new | existing) ;; *) die "state must be new or existing, not '$A_STATE'" ;; esac
    case $A_GHERKIN in yes | no) ;; *) die "gherkin must be yes or no, not '$A_GHERKIN'" ;; esac
    case $A_HOST in github | other) ;; *) die "host must be github or other, not '$A_HOST'" ;; esac
    for a in $A_AGENTS; do
        has_word "$KNOWN_AGENTS" "$a" || die "unknown agent '$a' (known: $KNOWN_AGENTS)"
    done
    dup=$(awk '{ print $1 }' "$WORK/apps" | LC_ALL=C sort | uniq -d | sed -n 1p)
    [ -z "$dup" ] || die "app path '$dup' appears twice: put all of its profiles on one line"
}

can_prompt() {
    ( : < /dev/tty ) 2>/dev/null
}

prompt() {
    # prompt <question> <default>: prints the reply, or the default when the reply is empty.
    if [ -n "$2" ]; then printf '%s [%s]: ' "$1" "$2" > /dev/tty; else printf '%s: ' "$1" > /dev/tty; fi
    IFS= read -r reply < /dev/tty || reply=
    reply=$(trim "$reply")
    [ -n "$reply" ] || reply=$2
    printf '%s\n' "$reply"
}

ask_apps() {
    : > "$WORK/apps"
    tty_say 'Enter each path with its profiles, one path per line. A frontend inside a server app'
    tty_say '(resources/js, ClientApp) is a path of its own. Leave the path blank when done.'
    while :; do
        path=$(prompt '  path (e.g. . or apps/api)' '')
        [ -n "$path" ] || break
        profs=$(prompt "  profiles for $path ($KNOWN_PROFILES)" '')
        add_app "$path $profs" || tty_say "  not valid: a relative path, then one or more of: $KNOWN_PROFILES"
    done
}

ask_questions() {
    tty_say ''
    tty_say "SpecForge $KIT_VERSION: rules for $TARGET"
    while :; do
        v=$(prompt 'New project (no code yet) or existing? new/existing' "$A_STATE")
        case $v in new | existing) A_STATE=$v; break ;; esac
    done
    if [ -s "$WORK/apps" ]; then
        tty_say 'Apps, by path and profiles (they become the Stacks table in AGENTS.md):'
        sed 's/^/  /' "$WORK/apps" > /dev/tty
        v=$(prompt 'Keep these? yes/no' yes)
    else
        tty_say 'No app found, or none decided yet. With none, every profile is installed and'
        tty_say 'bootstrap trims them once the stacks are decided.'
        v=no
    fi
    case $v in y | yes) ;; *) ask_apps ;; esac
    while :; do
        v=$(prompt "Agents that work here ($KNOWN_AGENTS)" "${A_AGENTS:-none}")
        [ "$v" = none ] && v=
        ok=1
        for a in $v; do has_word "$KNOWN_AGENTS" "$a" || ok=0; done
        if [ "$ok" = 1 ]; then A_AGENTS=$(squeeze "$v"); break; fi
        tty_say "  choose from: $KNOWN_AGENTS (or none)"
    done
    while :; do
        v=$(prompt 'Acceptance scenarios run by a Gherkin runner (Behat, Reqnroll, playwright-bdd)? yes/no' "$A_GHERKIN")
        case $v in y | yes) A_GHERKIN=yes; break ;; n | no) A_GHERKIN=no; break ;; esac
    done
    while :; do
        v=$(prompt 'Code host: github/other' "$A_HOST")
        case $v in github | other) A_HOST=$v; break ;; esac
    done
}

show_answers() {
    say "  state    $A_STATE"
    if [ -s "$WORK/apps" ]; then
        while read -r line; do say "  app      $line"; done < "$WORK/apps"
    else
        say '  apps     none decided: every profile is installed'
    fi
    say "  agents   ${A_AGENTS:-none}"
    say "  gherkin  $A_GHERKIN"
    say "  host     $A_HOST"
}

confirm() {
    v=$(prompt 'Proceed? yes/no' yes)
    case $v in y | yes) ;; *) say 'Nothing was changed.'; exit 0 ;; esac
}

# ---------------------------------------------------------------------------------------------
# What to install: profiles, the manifest's selection, rendered files

implied_by() {
    awk -v p="$1" '$1 == "implies" && $2 == p { print $3 }' "$SRC/manifest"
}

expand_profiles() {
    out=
    for p in $1; do
        has_word "$out" "$p" || out="$out $p"
        for q in $(implied_by "$p"); do has_word "$out" "$q" || out="$out $q"; done
    done
    squeeze "$out"
}

compute_profiles() {
    if [ -s "$WORK/apps" ]; then
        all=$(awk '{ $1 = ""; print }' "$WORK/apps" | tr '\n' ' ')
        PROFILES=$(expand_profiles "$all")
    else
        PROFILES=$KNOWN_PROFILES
    fi
}

select_targets() {
    (cd "$SRC/template" && find . -type f | sed 's|^\./||' | LC_ALL=C sort) > "$WORK/template.files"
    awk -v profiles=" $PROFILES " -v gherkin="$A_GHERKIN" -v host="$A_HOST" '
        /^[[:space:]]*(#|$)/ { next }
        $1 == "implies" { next }
        {
            sel = $1; path = $2; mode = ($3 == "" ? "file" : $3)
            if (mode != "file" && mode != "block" && mode != "seed" && mode != "generated") {
                print "manifest: unknown mode " mode > "/dev/stderr"; exit 3
            }
            ok = 0
            if (sel == "always") ok = 1
            else if (sel ~ /^profile=/) { if (index(profiles, " " substr(sel, 9) " ")) ok = 1 }
            else if (sel ~ /^gherkin=/) { if (substr(sel, 9) == gherkin) ok = 1 }
            else if (sel ~ /^host=/) { if (substr(sel, 6) == host) ok = 1 }
            else { print "manifest: unknown selector " sel > "/dev/stderr"; exit 3 }
            print path "\t" mode "\t" ok
        }' "$SRC/manifest" > "$WORK/manifest.eval" || die 'the manifest is malformed'
    awk -F '\t' '
        NR == FNR { p[NR] = $1; m[NR] = $2; k[NR] = $3; n = NR; next }
        {
            f = $0; matched = 0; inc = 0; mode = "file"
            for (i = 1; i <= n; i++) {
                if (p[i] == f || (substr(p[i], length(p[i])) == "/" && index(f, p[i]) == 1)) {
                    matched = 1; mode = m[i]; if (k[i] == 1) inc = 1
                }
            }
            if (!matched || inc) print mode "\t" f
        }' "$WORK/manifest.eval" "$WORK/template.files" > "$WORK/targets"
    cut -f2 "$WORK/targets" > "$WORK/target.paths"
}

stacks_rows() {
    while read -r path profs; do
        [ -n "$path" ] || continue
        names=
        links=
        for p in $(expand_profiles "$profs"); do
            names="$names${names:+ · }$(profile_name "$p")"
            links="$links${links:+ · }[\`stack-$p.md\`](docs/conventions/stack-$p.md)"
        done
        printf '| `%s` | %s <!-- bootstrap: versions --> | %s |\n' "$path" "$names" "$links"
    done < "$WORK/apps"
}

render_sources() {
    mkdir -p "$WORK/render/.ai"
    awk -v list=" $A_AGENTS " '
        /^# [a-z]+$/ { k = substr($0, 3); if (index(list, " " k " ")) { print k; next } }
        { print }' "$SRC/template/.ai/agents" > "$WORK/render/.ai/agents"
    stacks_rows > "$WORK/stacks"
    if [ -s "$WORK/stacks" ]; then
        awk -v rows="$WORK/stacks" '
            !done && index($0, "| <!-- bootstrap: `<path>` -->") == 1 {
                while ((getline l < rows) > 0) print l
                done = 1; next
            }
            { print }' "$SRC/template/AGENTS.md" > "$WORK/render/AGENTS.md"
    fi
}

source_of() {
    if [ -f "$WORK/render/$1" ]; then printf '%s\n' "$WORK/render/$1"; else printf '%s\n' "$SRC/template/$1"; fi
}

# ---------------------------------------------------------------------------------------------
# Writing, recording, the managed block

record() { printf '%s\n' "$*" >> "$WORK/lock.new"; }
note() { printf '%s\t%s\n' "$1" "$2" >> "$WORK/notes"; }

ensure_dir() {
    local d=$1
    [ -d "$d" ] && return 0
    ensure_dir "$(dirname "$d")" || return 1
    mkdir "$d" || return 1
    record "dir - $(relpath "$d")"
}

put() {
    # put <source> <destination>: atomic within the destination's directory, modes preserved.
    [ "$DRY_RUN" = 1 ] && return 0
    ensure_dir "$(dirname "$2")" || die "cannot create the directory for $2"
    cp -p "$1" "$2.specforge-tmp.$$" && mv -f "$2.specforge-tmp.$$" "$2" || die "cannot write $2"
}

drop() {
    [ "$DRY_RUN" = 1 ] && return 0
    rm -f "$1"
}

lock_entry() {
    awk -v p="$1" '
        ($1 == "file" || $1 == "seed" || $1 == "block" || $1 == "generated" || $1 == "deleted") && $NF == p {
            print; exit
        }' "$WORK/lock.old"
}

extract_block() {
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
        !done && $0 == b { inb = 1; found = 1; next }
        inb && $0 == e { inb = 0; done = 1; next }
        inb { print }
        END { if (!done) exit 1 }' "$1"
}

replace_block() {
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" -v nb="$2" '
        !done && $0 == b { print; while ((getline l < nb) > 0) print l; close(nb); skip = 1; next }
        skip && $0 == e { skip = 0; done = 1; print; next }
        !skip { print }' "$1"
}

append_block() {
    cat "$1"
    [ -z "$(tail -c 1 "$1")" ] || printf '\n'
    printf '\n%s\n' "$BEGIN_MARK"
    cat "$2"
    printf '%s\n' "$END_MARK"
}

strip_block() {
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
        { line[++n] = $0 }
        END {
            s = 0; t = 0
            for (i = 1; i <= n; i++) if (line[i] == b) { s = i; break }
            for (j = s; s && j <= n; j++) if (line[j] == e) { t = j; break }
            if (s && t && s > 1 && line[s - 1] == "" && (t == n || line[t + 1] == "")) s--
            for (i = 1; i <= n; i++) if (!(s && t && i >= s && i <= t)) print line[i]
        }' "$1"
}

write_incoming() {
    # write_incoming <source> <path>: the kit's complete version beside the project's file.
    put "$1" "$TARGET/$2$INCOMING"
    record "incoming $(hash_file "$1") $2$INCOMING"
    note kept "$2"
}

# ---------------------------------------------------------------------------------------------
# The policy, per file

apply_file() {
    # apply_file <path> <file|seed>
    p=$1
    kind=$2
    src=$(source_of "$p")
    dest="$TARGET/$p"
    new=$(hash_file "$src")
    set -- $(lock_entry "$p")
    okind=${1-}
    osha=${2-}
    if [ "$okind" = deleted ]; then record "deleted - $p"; note skipped "$p"; return 0; fi
    if [ ! -e "$dest" ] && [ ! -L "$dest" ]; then
        if [ -n "$okind" ]; then record "deleted - $p"; note skipped "$p"; return 0; fi
        put "$src" "$dest"
        record "$kind $new $p"
        note wrote "$p"
        return 0
    fi
    if [ -L "$dest" ] || [ ! -f "$dest" ]; then write_incoming "$src" "$p"; return 0; fi
    cur=$(hash_file "$dest")
    if [ "$cur" = "$new" ]; then record "$kind $new $p"; note unchanged "$p"; return 0; fi
    if [ -n "$okind" ]; then
        if [ "$kind" = seed ]; then record "seed $osha $p"; note unchanged "$p"; return 0; fi
        if [ "$cur" = "$osha" ]; then
            put "$src" "$dest"
            record "$kind $new $p"
            note updated "$p"
            return 0
        fi
        if [ "$new" = "$osha" ]; then
            # Changed by the project, not by the kit since it was last offered: theirs stands.
            record "$kind $osha $p"
            note unchanged "$p"
            return 0
        fi
    fi
    # The lock remembers the version offered, so the next update stays quiet until it changes.
    record "$kind $new $p"
    write_incoming "$src" "$p"
}

apply_block() {
    # apply_block <path>: only the text between the markers is the kit's.
    p=$1
    src=$(source_of "$p")
    dest="$TARGET/$p"
    extract_block "$src" > "$WORK/block.new" || die "the kit's $p has no specforge block"
    nb=$(hash_file "$WORK/block.new")
    set -- $(lock_entry "$p")
    okind=${1-}
    obsha=${2-}
    ofsha=${3-}
    if [ "$okind" = deleted ]; then record "deleted - $p"; note skipped "$p"; return 0; fi
    if [ ! -e "$dest" ] && [ ! -L "$dest" ]; then
        if [ -n "$okind" ]; then record "deleted - $p"; note skipped "$p"; return 0; fi
        put "$src" "$dest"
        record "block $nb $(hash_file "$src") $p"
        note wrote "$p"
        return 0
    fi
    if [ -L "$dest" ] || [ ! -f "$dest" ]; then write_incoming "$src" "$p"; return 0; fi
    cf=$(hash_file "$dest")
    if extract_block "$dest" > "$WORK/block.cur"; then
        cb=$(hash_file "$WORK/block.cur")
        if [ "$cb" = "$nb" ]; then
            if [ -n "$ofsha" ] && [ "$cf" = "$ofsha" ]; then record "block $nb $ofsha $p"; else record "block $nb - $p"; fi
            note unchanged "$p"
            return 0
        fi
        if [ -n "$okind" ] && [ "$cb" = "$obsha" ]; then
            replace_block "$dest" "$WORK/block.new" > "$WORK/merged"
            put "$WORK/merged" "$dest"
            if [ -n "$ofsha" ] && [ "$cf" = "$ofsha" ]; then
                record "block $nb $(hash_file "$WORK/merged") $p"
            else
                record "block $nb - $p"
            fi
            note updated "$p"
            return 0
        fi
        if [ -n "$okind" ] && [ "$nb" = "$obsha" ]; then
            record "block $obsha - $p"
            note unchanged "$p"
            return 0
        fi
        record "block $nb - $p"
        write_incoming "$src" "$p"
        return 0
    fi
    if [ -n "$okind" ]; then
        # The markers were removed: the file is the project's, offered the kit's version only when
        # that version changes.
        record "block $nb - $p"
        if [ "$nb" = "$obsha" ]; then note unchanged "$p"; else write_incoming "$src" "$p"; fi
        return 0
    fi
    if [ "$p" = CLAUDE.md ] && grep -q '^@AGENTS\.md' "$dest"; then
        note unchanged "$p"
        return 0
    fi
    append_block "$dest" "$WORK/block.new" > "$WORK/merged"
    put "$WORK/merged" "$dest"
    record "block $nb - $p"
    note appended "$p"
    if [ "$p" = AGENTS.md ]; then write_incoming "$src" "$p"; fi
}

apply_dropped() {
    # Files the kit installed that are no longer selected: taken back while unmodified.
    awk '$1 == "file" || $1 == "seed" { print $2, $NF }' "$WORK/lock.old" > "$WORK/dropped"
    while read -r sha p; do
        grep -qxF "$p" "$WORK/target.paths" && continue
        dest="$TARGET/$p"
        if [ -f "$dest" ] && [ ! -L "$dest" ] && [ "$(hash_file "$dest")" = "$sha" ]; then
            drop "$dest"
            note removed "$p"
        elif [ -e "$dest" ]; then
            note left "$p"
        fi
    done < "$WORK/dropped"
}

carry_over() {
    # Directories the installer created, and incoming files not yet reconciled.
    while read -r kind sha p; do
        case $kind in
            dir) [ -d "$TARGET/$p" ] && record "dir - $p" ;;
            incoming) [ -f "$TARGET/$p" ] && record "incoming $sha $p" ;;
        esac
    done < "$WORK/lock.old"
}

run_sync() {
    SYNC_OUT=
    SYNC_STATUS=0
    if [ "$DRY_RUN" = 1 ]; then return 0; fi
    : > "$WORK/dirs.before"
    for d in $TRACKED_DIRS; do [ -e "$TARGET/$d" ] && printf '%s\n' "$d" >> "$WORK/dirs.before"; done
    gem_before=0
    [ -e "$TARGET/.gemini/settings.json" ] && gem_before=1
    if [ -x "$TARGET/.ai/bin/sync-rules" ]; then
        SYNC_OUT=$("$TARGET/.ai/bin/sync-rules" 2>&1) || SYNC_STATUS=$?
    else
        SYNC_OUT='.ai/bin/sync-rules is missing or not executable: agent rule files were not generated'
        SYNC_STATUS=1
    fi
    for d in $TRACKED_DIRS; do
        if [ -d "$TARGET/$d" ] && ! grep -qxF "$d" "$WORK/dirs.before"; then record "dir - $d"; fi
    done
    if [ -f "$TARGET/.ai/rules/index.md" ]; then
        record "generated $(hash_file "$TARGET/.ai/rules/index.md") .ai/rules/index.md"
    fi
    old=$(awk '$1 == "generated" && $NF == ".gemini/settings.json"' "$WORK/lock.old")
    if [ -n "$old" ] && [ -f "$TARGET/.gemini/settings.json" ]; then
        record "$old"
    elif [ "$gem_before" = 0 ] && [ -f "$TARGET/.gemini/settings.json" ]; then
        record "generated $(hash_file "$TARGET/.gemini/settings.json") .gemini/settings.json"
    fi
}

write_lock() {
    [ "$DRY_RUN" = 1 ] && return 0
    {
        printf '# Written by the SpecForge installer. Do not edit; commit it with the project.\n'
        printf 'version %s\n' "$KIT_VERSION"
        printf 'installed %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
        printf 'commit %s\n' "$GIT_COMMIT"
        printf 'answer state=%s\n' "$A_STATE"
        while read -r line; do [ -n "$line" ] && printf 'answer app=%s\n' "$line"; done < "$WORK/apps"
        printf 'answer agents=%s\n' "$A_AGENTS"
        printf 'answer gherkin=%s\n' "$A_GHERKIN"
        printf 'answer host=%s\n' "$A_HOST"
        # One entry per path, the last recorded winning; sorted by path.
        awk '{ last[$NF] = $0; if (!($NF in seen)) { seen[$NF] = 1; order[++n] = $NF } }
             END { for (i = 1; i <= n; i++) print order[i] "\t" last[order[i]] }' "$WORK/lock.new" |
            LC_ALL=C sort | cut -f2-
    } > "$WORK/lock.final"
    put "$WORK/lock.final" "$LOCK"
}

# ---------------------------------------------------------------------------------------------
# Reporting

count() { awk -F '\t' -v a="$1" '$1 == a' "$WORK/notes" | wc -l | tr -d ' '; }

list() {
    awk -F '\t' -v a="$1" '$1 == a { print "    " $2 }' "$WORK/notes"
}

summarize() {
    say ''
    if [ "$DRY_RUN" = 1 ]; then say "Dry run: SpecForge $KIT_VERSION would change $TARGET as follows. Nothing was changed."; fi
    say "  wrote $(count wrote) · updated $(count updated) · appended to $(count appended) · unchanged $(count unchanged) · kept yours $(count kept) · removed $(count removed)"
    if [ "$(count appended)" -gt 0 ]; then
        say "  The rules' block was appended to your file:"
        list appended
    fi
    if [ "$(count kept)" -gt 0 ]; then
        say "  Kept yours; the kit's version is beside each as <file>$INCOMING:"
        list kept
    fi
    if [ "$(count left)" -gt 0 ]; then
        say '  No longer part of the rules, but kept because you changed them:'
        list left
    fi
    if [ "$(count skipped)" -gt 0 ]; then
        say '  Deleted by you, and not restored:'
        list skipped
    fi
    if [ -n "${SYNC_OUT-}" ]; then
        problems=$(printf '%s\n' "$SYNC_OUT" | grep -v '^wrote: ' | grep -v '^removed: ' || true)
        if [ "${SYNC_STATUS:-0}" != 0 ] || [ -n "$problems" ]; then
            say '  .ai/bin/sync-rules reported:'
            printf '%s\n' "$problems" | sed 's/^/    /'
        fi
    fi
}

handover() {
    [ "$DRY_RUN" = 1 ] && return 0
    say ''
    if [ -n "$A_AGENTS" ]; then
        say "Agents: $A_AGENTS. Their rule files are generated from .ai/rules/ by .ai/bin/sync-rules."
    else
        say 'Agents: none chosen. Every agent still reads AGENTS.md; list yours in .ai/agents, then run .ai/bin/sync-rules.'
    fi
    say ''
    say 'Next:'
    n=1
    if [ "$CMD" = install ]; then
        if [ "$A_STATE" = new ]; then
            say "  $n. Open the project in your agent and say: Run the bootstrap prompt."
        else
            say "  $n. Open the project in your agent and say: Run the adopt prompt."
        fi
        n=$((n + 1))
    fi
    if [ "$(count kept)" -gt 0 ]; then
        say "  $n. Reconcile each <file>$INCOMING, then delete it; .ai/bin/check lists them until then."
        n=$((n + 1))
    fi
    if [ "$CMD" = update ] && [ "${APPS_CHANGED:-0}" = 1 ]; then
        say "  $n. The apps changed: bring the Stacks table in AGENTS.md in line with them."
        n=$((n + 1))
    fi
    if [ "$CMD" = install ]; then
        say "  $n. Add .ai/bin/check to CI, beside each app's lint, type check and tests."
        n=$((n + 1))
    fi
    if detect_boost; then
        say "  $n. Laravel Boost is installed: run php artisan boost:install to refresh its guidelines."
        n=$((n + 1))
    fi
    if [ -e "$TARGET/.git" ]; then
        say "  $n. Commit the rules together with $LOCK_REL."
    fi
}

# ---------------------------------------------------------------------------------------------
# Commands

install_or_update() {
    compute_profiles
    render_sources
    select_targets
    carry_over
    while IFS="$(printf '\t')" read -r mode p; do
        case $mode in
            file | seed) apply_file "$p" "$mode" ;;
            block) apply_block "$p" ;;
            generated) ;;
        esac
    done < "$WORK/targets"
    apply_dropped
    run_sync
    write_lock
    summarize
    handover
}

cmd_install() {
    if [ -f "$LOCK" ]; then
        v=$(awk '$1 == "version" { print $2; exit }' "$LOCK")
        die "SpecForge ${v:-} is already installed in $TARGET: run update instead"
    fi
    fetch_source
    detect_apps
    cp "$WORK/detected.apps" "$WORK/apps"
    A_STATE=$(detect_state)
    A_AGENTS=$(detect_agents)
    A_GHERKIN=$(detect_gherkin)
    A_HOST=$(detect_host)
    INTERACTIVE=0
    if [ -n "$ANSWERS_FILE" ]; then
        load_answers
    elif [ "$ASSUME_YES" = 0 ]; then
        can_prompt || die 'no terminal to ask on: pass --answers FILE, or --yes to take what was detected'
        INTERACTIVE=1
    fi
    validate_answers
    if [ "$INTERACTIVE" = 1 ]; then
        ask_questions
        validate_answers
    fi
    say ''
    say "SpecForge $KIT_VERSION into $TARGET"
    show_answers
    git_report
    if [ "$INTERACTIVE" = 1 ] && [ "$DRY_RUN" = 0 ]; then confirm; fi
    install_or_update
}

cmd_update() {
    [ -f "$LOCK" ] || die "SpecForge is not installed in $TARGET (no $LOCK_REL): run install"
    cp "$LOCK" "$WORK/lock.old"
    fetch_source
    A_STATE=$(awk '$1 == "answer" && $2 ~ /^state=/ { sub(/^state=/, "", $2); print $2; exit }' "$WORK/lock.old")
    A_GHERKIN=$(awk '$1 == "answer" && $2 ~ /^gherkin=/ { sub(/^gherkin=/, "", $2); print $2; exit }' "$WORK/lock.old")
    A_HOST=$(awk '$1 == "answer" && $2 ~ /^host=/ { sub(/^host=/, "", $2); print $2; exit }' "$WORK/lock.old")
    awk '$1 == "answer" && $2 ~ /^app=/ { sub(/^answer[ \t]+app=/, ""); print }' "$WORK/lock.old" > "$WORK/apps"
    if [ -f "$TARGET/.ai/agents" ]; then
        A_AGENTS=$(awk '!/^[[:space:]]*#/ && NF { printf "%s ", $1 }' "$TARGET/.ai/agents")
    else
        A_AGENTS=$(awk '$1 == "answer" && $2 ~ /^agents=/ { sub(/^answer[ \t]+agents=/, ""); print; exit }' "$WORK/lock.old")
    fi
    A_AGENTS=$(squeeze "$A_AGENTS")
    cp "$WORK/apps" "$WORK/apps.before"
    if [ -n "$ANSWERS_FILE" ]; then
        load_answers
    elif [ "$RECONFIGURE" = 1 ]; then
        can_prompt || die 'no terminal to ask on: pass --answers FILE'
        validate_answers
        ask_questions
    fi
    validate_answers
    APPS_CHANGED=0
    cmp -s "$WORK/apps" "$WORK/apps.before" || APPS_CHANGED=1
    say ''
    old=$(awk '$1 == "version" { print $2; exit }' "$WORK/lock.old")
    say "SpecForge ${old:-?} → $KIT_VERSION in $TARGET"
    show_answers
    git_report
    install_or_update
}

cmd_remove() {
    [ -f "$LOCK" ] || die "SpecForge is not installed in $TARGET (no $LOCK_REL)"
    cp "$LOCK" "$WORK/lock.old"
    say "Removing SpecForge from $TARGET"
    set +f
    for d in $AGENT_DIRS; do
        for f in "$TARGET/$d"/ai-*; do
            [ -f "$f" ] || continue
            if grep -qF "$GEN_MARK" "$f"; then drop "$f"; note removed "$(relpath "$f")"; fi
        done
    done
    set -f
    while read -r kind a b c; do
        case $kind in
            file | seed | generated | incoming)
                p=$b
                dest="$TARGET/$p"
                [ -e "$dest" ] || continue
                if [ -f "$dest" ] && [ ! -L "$dest" ] && [ "$(hash_file "$dest")" = "$a" ]; then
                    drop "$dest"
                    note removed "$p"
                else
                    note left "$p"
                fi ;;
            block)
                p=$c
                dest="$TARGET/$p"
                [ -f "$dest" ] || continue
                if [ "$b" != - ] && [ "$(hash_file "$dest")" = "$b" ]; then
                    drop "$dest"
                    note removed "$p"
                elif extract_block "$dest" > "$WORK/block.cur" && [ "$(hash_file "$WORK/block.cur")" = "$a" ]; then
                    strip_block "$dest" > "$WORK/stripped"
                    put "$WORK/stripped" "$dest"
                    note stripped "$p"
                else
                    note left "$p"
                fi ;;
        esac
    done < "$WORK/lock.old"
    drop "$LOCK"
    awk '$1 == "dir" { print $3 }' "$WORK/lock.old" | LC_ALL=C sort -r > "$WORK/dirs"
    while read -r d; do
        [ "$DRY_RUN" = 1 ] || rmdir "$TARGET/$d" 2>/dev/null || true
    done < "$WORK/dirs"
    say ''
    if [ "$DRY_RUN" = 1 ]; then say 'Dry run: nothing was changed.'; fi
    say "  removed $(count removed) · block taken out of $(count stripped) · kept because you changed them $(count left)"
    if [ "$(count stripped)" -gt 0 ]; then
        say '  The rules block was taken out of:'
        list stripped
    fi
    if [ "$(count left)" -gt 0 ]; then
        say '  Kept, because you changed them:'
        list left
    fi
}

main() {
    set -u
    set -f
    parse_args "$@"
    resolve_target
    make_work
    pick_hasher
    case $CMD in
        install) cmd_install ;;
        update) cmd_update ;;
        remove) cmd_remove ;;
    esac
}

main "$@"
